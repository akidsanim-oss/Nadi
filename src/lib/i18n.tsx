interface LangCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (k: string) => string;
  dir: 'rtl' | 'ltr';
  isAr: boolean;
  pname: (p: { nameAr: string; nameFr: string }) => string;
  pdesc: (p: { descAr: string; descFr: string }) => string;
  pshort: (p: { shortAr: string; shortFr: string }) => string;
}

const Ctx = createContext<LangCtx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try { return (localStorage.getItem('jawhara-locale') as Locale) || 'ar'; } catch { return 'ar'; }
  });
  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    try { localStorage.setItem('jawhara-locale', locale); } catch { /* noop */ }
  }, [locale]);
  const setLocale = (l: Locale) => setLocaleState(l);
  const t = (k: string) => (locale === 'ar' ? AR[k] ?? FR[k] ?? k : FR[k] ?? AR[k] ?? k);
  const ctx: LangCtx = {
    locale, setLocale, t,
    dir: locale === 'ar' ? 'rtl' : 'ltr',
    isAr: locale === 'ar',
    pname: (p) => (locale === 'ar' ? p.nameAr : p.nameFr),
    pdesc: (p) => (locale === 'ar' ? p.descAr : p.descFr),
    pshort: (p) => (locale === 'ar' ? p.shortAr : p.shortFr),
  };
  return <Ctx.Provider value={ctx}>{children}</Ctx.Provider>;
}

export function useLang(): LangCtx {
  const v = useContext(Ctx);
  if (!v) throw new Error('useLang outside provider');
  return v;
}

export function mad(n: number, locale: Locale): string {
  const num = new Intl.NumberFormat(locale === 'ar' ? 'ar-MA' : 'fr-MA').format(Math.round(n));
  return `${num} ${locale === 'ar' ? 'درهم' : 'DH'}`;
}
